export type TranslationKey = Key;
export const dictionaries = { en, zh, ja };
export function translator(language: Language) {
  return (key: Key) => dictionaries[language][key];
}
export function errorText(
  error: unknown,
  t: ReturnType<typeof translator>,
): string {
  const key = error instanceof Error ? error.message : "requestFailed";
  return key in en ? t(key as Key) : t("requestFailed");
}
