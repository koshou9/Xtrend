export const aiT = (language: Language) => (key: Key) =>
  ({ en, zh, ja })[language][key];
export function templateName(
  template: { id: string; name: string },
  language: Language,
) {
  return zh[template.id as Key] === template.name
    ? aiT(language)(template.id as Key)
    : template.name;
}
